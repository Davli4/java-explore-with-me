async function main() {
  const existing = await call('GET', '/admin/users?from=0&size=1');
  if (existing.length) {
    console.log('В базе уже есть данные — демо-набор не загружаю.');
    return;
  }
  const users = [];
  for (const [name, email] of USERS) users.push(await call('POST', '/admin/users', { name, email }));
  const cats = [];
  for (const name of CATEGORIES) cats.push(await call('POST', '/admin/categories', { name }));

  const events = [];
  for (const [u, c, days, hour, limit, moderation, paid, title, annotation, description, lat, lon] of EVENTS) {
    events.push(await call('POST', `/users/${users[u].id}/events`, {
      title, annotation, description,
      category: cats[c].id,
      eventDate: inDays(days, hour),
      participantLimit: limit,
      requestModeration: moderation,
      paid,
      location: { lat, lon },
    }));
  }

  // Модерация: последние два оставляем на проверке, предпоследнее отклоняем
  for (let i = 0; i < events.length - 2; i++) {
    await call('PATCH', `/admin/events/${events[i].id}`, { stateAction: 'PUBLISH_EVENT' });
  }
  await call('PATCH', `/admin/events/${events[events.length - 2].id}`, { stateAction: 'REJECT_EVENT' });

  // Заявки участников
  const join = async (u, e) => call('POST', `/users/${users[u].id}/requests?eventId=${events[e].id}`);
  const plan = [[1, 0], [2, 0], [3, 0], [4, 0], [0, 1], [2, 1], [5, 1], [0, 2], [3, 2], [4, 2], [5, 2],
    [0, 3], [2, 3], [5, 3], [1, 4], [2, 4], [0, 5], [1, 5], [3, 5], [4, 5], [2, 6], [5, 7]];
  const reqs = {};
  for (const [u, e] of plan) {
    const r = await join(u, e);
    (reqs[e] = reqs[e] || []).push(r);
  }
  // Организаторы подтверждают часть заявок
  const confirm = async (e, n) => {
    const pending = reqs[e].filter((r) => r.status === 'PENDING').slice(0, n).map((r) => r.id);
    if (pending.length) {
      await call('PATCH', `/users/${users[EVENTS[e][0]].id}/events/${events[e].id}/requests`, { requestIds: pending, status: 'CONFIRMED' });
    }
  };
  await confirm(0, 3);
  await confirm(2, 3);
  await confirm(3, 2);
  await confirm(5, 3);

  // Комментарии
  const comment = (u, e, text) => call('POST', `/users/${users[u].id}/comments/${events[e].id}`, { text });
  await comment(1, 0, 'А «Каркассон» с дополнениями будет? Очень хочется попробовать «Купцов и строителей».');
  await comment(0, 0, 'Будет базовая коробка и «Таверны и соборы». «Купцов» принесите, если есть — сыграем!');
  await comment(4, 2, 'Есть ли возможность доехать на электричке? И нужны ли палатки?');
  await comment(2, 2, 'Да, электричка до станции «Ждановичи», дальше пешком 15 минут. Палатки не нужны, вернёмся к вечеру.');
  await comment(3, 5, 'Мы придём командой из четырёх человек, место для нас найдётся?');
  await comment(0, 1, 'Отличный маршрут, была в прошлый раз — очень рекомендую!');

  // Подборки
  await call('POST', '/admin/compilations', { title: 'Активные выходные', pinned: true, events: [events[1].id, events[2].id, events[7].id] });
  await call('POST', '/admin/compilations', { title: 'Вечера в компании', pinned: true, events: [events[0].id, events[4].id, events[5].id, events[6].id] });
  await call('POST', '/admin/compilations', { title: 'Бесплатно', pinned: false, events: [events[0].id, events[1].id, events[2].id, events[6].id, events[8].id] });

  console.log(`Готово: ${users.length} пользователей, ${cats.length} категорий, ${events.length} событий.`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
